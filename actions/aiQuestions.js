"use server";

import { GoogleGenAI } from "@google/genai";
import { currentUser } from "@clerk/nextjs/server";

const CATEGORY_PROMPTS = {
  FULLSTACK:
    "Frontend architecture, React, JavaScript, TypeScript, backend APIs, Node.js, databases, authentication, state management, caching, testing, deployment, security, performance, and full-stack architecture",

  FRONTEND:
    "React, JavaScript, TypeScript, HTML, CSS, browser APIs, state management, performance optimization, accessibility, responsive design, testing, security, and frontend architecture",

  BACKEND:
    "Node.js, JavaScript, TypeScript, REST APIs, authentication, authorization, SQL, NoSQL, databases, caching, error handling, testing, security, performance, scalability, and backend architecture",

  DSA: "Arrays, strings, hash maps, stacks, queues, linked lists, trees, graphs, sorting, searching, recursion, dynamic programming, greedy algorithms, problem solving, and time and space complexity",

  SYSTEM_DESIGN:
    "Distributed systems, scalability, load balancing, caching, databases, database sharding, replication, message queues, microservices, API design, fault tolerance, consistency, availability, monitoring, and system architecture",

  BEHAVIORAL:
    "Leadership, teamwork, communication, conflict resolution, ownership, decision making, handling failure, adaptability, mentoring, career growth, workplace scenarios, and STAR method",

  DEVOPS:
    "Linux, networking, CI/CD, Git, Docker, Kubernetes, cloud infrastructure, infrastructure as code, monitoring, logging, alerting, security, scalability, deployment strategies, and incident response",

  ANDROID:
    "React Native, iOS, Android, mobile UI, navigation, state management, performance, offline support, networking, local storage, push notifications, app lifecycle, testing, security, and mobile architecture",
};

export async function generateInterviewQuestions({ category }) {
  const user = await currentUser();
  if (!user) throw new Error("Unauthorized");

  if (!category || !CATEGORY_PROMPTS[category])
    throw new Error("Invalid category");

  const genAI = new GoogleGenAI({
    apiKey: process.env.GEMINI_API_KEY,
  });

  const prompt = `
  You are an expert technical interviewer conducting a real software
  engineering interview.

  Generate exactly 6 interview questions for a ${category} interview.

  Focus areas:
  ${CATEGORY_PROMPTS[category]}

  Requirements:
  - Questions should be realistic interview questions, not trivia.
  - Mix conceptual, practical, and scenario-based questions.
  - Start with moderate difficulty and gradually increase difficulty.
  - Avoid duplicate or closely related questions.
  - Questions should test understanding rather than memorization.
  - For technical categories, include at least one practical problem-solving
    or debugging-oriented question.
  - For DSA, include algorithmic problem-solving questions and expected
    time/space complexity.
  - For System Design, include architecture and trade-off questions.
  - For Behavioral, use realistic workplace scenarios.
  - Answers should be concise but technically accurate.
  - Each answer should be 2-4 sentences.
  - Do not include information outside the requested category.

  Return exactly this JSON structure:
  [
    {
      "question": "string",
      "answer": "string"
    }
  ]

  Return ONLY valid JSON. No markdown, no code fences, and no additional text.
  `;

  const response = await genAI.models.generateContent({
    model: "gemini-3.8-flash",
    contents: prompt,
    config: {
      responseMimeType: "application/json",
    },
  });

  const text = response.text.trim();
  if (!text) throw new Error("No response generated by Gemini");

  const questions = JSON.parse(text);

  return {
    questions,
  };
}
